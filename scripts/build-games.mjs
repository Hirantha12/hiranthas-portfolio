// npm run games: checks every opening in scripts/game-lines.mjs with chess.js (legal moves,
// 9 moves each, the last one checkmate by Black) and writes src/data/games.js for the site.
// The site itself doesn't need chess.js: it uses the from/to squares saved here.
import { writeFileSync } from 'node:fs';
import { Chess } from 'chess.js';
import { LINES } from './game-lines.mjs';

const MOVES = 9;
const NAME = { p: 'pawn', n: 'knight', b: 'bishop', r: 'rook', q: 'queen', k: 'king' };

// What Hirantha just did, in plain words.
function whiteSays(m) {
  if (m.flags.includes('k') || m.flags.includes('q')) return 'He castled.';
  const check = m.san.includes('+') ? ' Check!' : '';
  if (m.captured) return `He took your ${NAME[m.captured]} on ${m.to}.${check}`;
  if (m.piece === 'p') return `He pushed a pawn to ${m.to}.${check}`;
  if (m.piece === 'q') return `His queen came out to ${m.to}.${check}`;
  if (m.piece === 'k') return `His king stepped to ${m.to}.${check}`;
  const developing = m.from[1] === '1';
  return `${developing ? 'He developed his' : 'His'} ${NAME[m.piece]} ${developing ? 'to' : 'went to'} ${m.to}.${check}`;
}
// What the visitor should play.
function blackSays(m, last) {
  if (last) return 'He missed the threat. Deliver checkmate!';
  if (m.flags.includes('k') || m.flags.includes('q')) return 'Castle your king to safety.';
  if (m.captured) return `Take his ${NAME[m.captured]} on ${m.to}${m.san.includes('+') ? ', with check' : ''}.`;
  if (m.san.includes('+')) return `Give check with your ${NAME[m.piece]}.`;
  if (m.piece === 'p') return `Push your pawn to ${m.to}.`;
  return `Bring your ${NAME[m.piece]} to ${m.to}.`;
}

const games = LINES.map(([id, name, idea, line]) => {
  const sans = line.trim().split(/\s+/).filter((t) => !/^\d+\.$/.test(t)).map((t) => t.replace(/^\d+\.+/, ''));
  if (sans.length !== MOVES * 2) throw new Error(`${id}: ${sans.length / 2} moves, need ${MOVES}`);
  const c = new Chess(), ms = [];
  for (const s of sans) {
    let m; try { m = c.move(s); } catch { throw new Error(`${id}: illegal move ${s}`); }
    if (m.flags.includes('e') || m.flags.includes('p')) throw new Error(`${id}: en passant and promotion aren't animated, avoid ${s}`);
    ms.push(m);
  }
  if (!c.isCheckmate()) throw new Error(`${id}: the last move is not checkmate`);
  const moves = [];
  for (let k = 0; k < MOVES; k++) {
    const w = ms[2 * k], b = ms[2 * k + 1];
    moves.push({ white: [w.from, w.to, w.san], black: [b.from, b.to, `…${b.san}`], say: `${whiteSays(w)} ${blackSays(b, k === MOVES - 1)}` });
  }
  return { id, name, idea, line, moves };
});

const J = JSON.stringify;
const body = games.map((g) => `  { id: ${J(g.id)}, name: ${J(g.name)},
    idea: ${J(g.idea)},
    line: ${J(g.line)},
    moves: [
${g.moves.map((m) => `      { white: ${J(m.white)}, black: ${J(m.black)}, say: ${J(m.say)} },`).join('\n')}
    ] },`).join('\n');

const out = `// Generated by \`npm run games\` from scripts/game-lines.mjs. Don't edit by hand.
// ${games.length} openings, each checked with chess.js: legal, ${MOVES} moves, Black mates on move ${MOVES}.
export const GAMES = [
${body}
];

// A random opening, never the same one twice in a row for the same visitor.
export function pickGame() {
  let last = null;
  try { last = localStorage.getItem('hg-last-game'); } catch (e) { /* storage blocked */ }
  const choices = GAMES.filter((g) => g.id !== last);
  const g = choices[Math.floor(Math.random() * choices.length)];
  try { localStorage.setItem('hg-last-game', g.id); } catch (e) { /* storage blocked */ }
  return g;
}
`;
writeFileSync(new URL('../src/data/games.js', import.meta.url), out);
console.log(`${games.length} openings checked and written to src/data/games.js`);
